#!/usr/bin/env node
// Writes infra/prod/.env for infra/compose.prod.yml: random passwords, the internal service secret
// and a fresh JWT signing key. Fill in the few external keys it lists at the end (DEPLOY.md).
//
//   node scripts/gen-prod-env.mjs --domain codebattle.duckdns.org
//   node scripts/gen-prod-env.mjs --domain play.example.com --tunnel     (Cloudflare Tunnel: Caddy on :80)
//
// Refuses to overwrite an existing file (that would lock you out of the databases): pass --force
// only for a fresh install.
import { generateKeyPairSync, randomBytes, randomUUID } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const args = process.argv.slice(2);
const arg = (name) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const domain = arg('domain');
if (!domain || domain.startsWith('-')) {
  console.error('usage: node scripts/gen-prod-env.mjs --domain <your domain> [--tunnel] [--force]');
  process.exit(1);
}
const tunnel = args.includes('--tunnel');
const file = join(import.meta.dirname, '..', 'infra', 'prod', '.env');
if (existsSync(file) && !args.includes('--force')) {
  console.error(
    `${file} already exists. Keep it (it holds the database passwords). Use --force only on a fresh install.`,
  );
  process.exit(1);
}

const secret = (bytes = 24) => randomBytes(bytes).toString('base64url');
const { privateKey } = generateKeyPairSync('ed25519');
const jwk = privateKey.export({ format: 'jwk' });
const kid = `k-${new Date().toISOString().slice(0, 10)}-${randomUUID().slice(0, 8)}`;
const jwtKeys = JSON.stringify([{ ...jwk, kid, alg: 'EdDSA', use: 'sig' }]);

const lines = [
  '# Code Battle production secrets. Generated by scripts/gen-prod-env.mjs. NEVER commit or share.',
  '',
  '# ---- site',
  `DOMAIN=${domain}`,
  `SITE_ADDRESS=${tunnel ? ':80' : domain}`,
  '',
  '# ---- generated (do not change after the first start: the databases use these)',
  `POSTGRES_PASSWORD=${secret()}`,
  ...['IDENTITY', 'USERS', 'NOTIFICATION', 'PROBLEM', 'JUDGE', 'BATTLE', 'RATING', 'AI'].map(
    (s) => `PG_PASS_${s}=${secret()}`,
  ),
  `REDIS_PASSWORD=${secret()}`,
  `INTERNAL_SERVICE_SECRET=${secret(32)}`,
  `JWT_KEYS='${jwtKeys}'`,
  `GRAFANA_ADMIN_PASSWORD=${secret(12)}`,
  '',
  '# ---- judge: RapidAPI Judge0 CE (free plan: 50 requests a day; a submit uses about 2)',
  'JUDGE0_URL=https://judge0-ce.p.rapidapi.com',
  'JUDGE0_AUTH=rapidapi',
  'JUDGE0_API_KEY=FILL_ME_rapidapi_key',
  'JUDGE0_DAILY_BUDGET=50',
  'MATCH_RESERVE_CALLS=10',
  '',
  '# ---- email: Brevo (free: 300 a day). EMAIL_FROM must be a verified sender in Brevo.',
  'BREVO_API_KEY=FILL_ME_brevo_api_key',
  'EMAIL_FROM=FILL_ME_verified_sender@example.com',
  'EMAIL_FROM_NAME=Code Battle',
  '',
  '# ---- AI: Groq free tier (https://console.groq.com/keys). Empty = AI features off, the rest works.',
  'GROQ_API_KEY=',
  '',
  '# ---- optional',
  '# Cloudflare Tunnel (laptop hosting, DEPLOY.md option B)',
  `CLOUDFLARE_TUNNEL_TOKEN=${tunnel ? 'FILL_ME_tunnel_token' : ''}`,
  '# avatars (leave empty to disable uploads)',
  'CLOUDINARY_CLOUD_NAME=',
  'CLOUDINARY_API_KEY=',
  'CLOUDINARY_API_SECRET=',
  '# alert emails from Grafana (infra/observability/README.md)',
  'ALERT_EMAIL=',
  'GF_SMTP_ENABLED=false',
  'GF_SMTP_HOST=',
  'GF_SMTP_USER=',
  'GF_SMTP_PASSWORD=',
  'GF_SMTP_FROM_ADDRESS=',
  '',
];
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, lines.join('\n'), { mode: 0o600 });
console.log(`wrote ${file}`);
console.log(
  'Now fill in every FILL_ME value:',
  ['JUDGE0_API_KEY', 'BREVO_API_KEY', 'EMAIL_FROM']
    .concat(tunnel ? ['CLOUDFLARE_TUNNEL_TOKEN'] : [])
    .join(', '),
);
